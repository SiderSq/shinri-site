// Helper to convert character object to case suspect structure
export function createSuspectFromCharacter(char, index, isVictim = false, isCulprit = false) {
  const idStr = String(index + 1).padStart(2, '0');
  const maskedName = `Фигурант #${idStr} // ${char.name.replace(/[а-яА-ЯёЁa-zA-Z0-9-]/g, '■')}`;
  const maskedRole = `Абсолютный(-ая) ${char.role.replace(/Абсолютный(-ая)?\s*/i, '').replace(/[а-яА-ЯёЁa-zA-Z0-9-]/g, '■')}`;

  let status = 'Фигурант дела';
  if (isVictim) status = 'Жертва преступления';
  else if (isCulprit) status = 'Подозреваемый (Зачернённый)';

  return {
    id: idStr,
    maskedName,
    realName: char.name,
    maskedRole,
    realRole: char.role,
    alibi: `По заявлению фигуранта: нахождение в жилом блоке до момента объявления Монокумы. Отрицает причастность к инциденту.`,
    status,
    isVictim: Boolean(isVictim),
    isCulprit: Boolean(isCulprit),
    puzzle: {
      question: char.defaultRiddle,
      hint: char.defaultHint,
      answers: char.defaultAnswers
    }
  };
}
